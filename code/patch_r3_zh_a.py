def one(s, old, new, tag):
    if s.count(old) != 1:
        raise SystemExit('[%s] 匹配 %d 次\n%s' % (tag, s.count(old), old[:140]))
    LOG.append('ok  ' + tag)
    return s.replace(old, new)


def para_has(s, substr, new_para, tag):
    parts = s.split('\n\n')
    hit = [i for i, p in enumerate(parts) if substr in p[:400]]
    if len(hit) != 1:
        raise SystemExit('[%s] 段落匹配 %d 次' % (tag, len(hit)))
    parts[hit[0]] = new_para
    LOG.append('ok  ' + tag)
    return '\n\n'.join(parts)


